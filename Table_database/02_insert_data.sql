-- Pemeriksaan cepat jumlah data
-- Harapan: PELANGGAN 6, KARYAWAN 5, MENU 10, BAHAN_BAKU 11,
--          TRANSAKSI 12, DETAIL_TRANSAKSI 21, KOMPOSISI_MENU 21
