UNION ALL SELECT 'KARYAWAN',         COUNT(*) FROM KARYAWAN
UNION ALL SELECT 'MENU',             COUNT(*) FROM MENU
UNION ALL SELECT 'BAHAN_BAKU',       COUNT(*) FROM BAHAN_BAKU
UNION ALL SELECT 'TRANSAKSI',        COUNT(*) FROM TRANSAKSI
UNION ALL SELECT 'DETAIL_TRANSAKSI', COUNT(*) FROM DETAIL_TRANSAKSI
UNION ALL SELECT 'KOMPOSISI_MENU',   COUNT(*) FROM KOMPOSISI_MENU;
