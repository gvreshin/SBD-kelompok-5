-- Urutan : PELANGGAN -> KARYAWAN -> MENU -> BAHAN_BAKU ->
--          TRANSAKSI -> DETAIL_TRANSAKSI -> KOMPOSISI_MENU
-- Konvensi nama constraint:
--   PK_<tabel>, FK_<anak>_<induk>, UK_<tabel>_<kolom>, CK_<tabel>_<aturan>
-- =====================================================================

