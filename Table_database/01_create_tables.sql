-- ---------------------------------------------------------------------
-- Catatan ID otomatis:
-- GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
--  * Jika ID tidak diisi (atau NULL), Oracle membuat ID mulai dari 100.
--  * ID manual 1-99 dipakai untuk data dummy agar FK pasti benar
--    dan tidak bentrok dengan ID otomatis.
-- ---------------------------------------------------------------------

-- 1. PELANGGAN --------------------------------------------------------
CREATE TABLE PELANGGAN (
    ID_PELANGGAN    NUMBER(10)
                    GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
                    NOT NULL,
    NAMA_PELANGGAN  VARCHAR2(100)  NOT NULL,
    NO_TELEPON      VARCHAR2(15)   NOT NULL,
    EMAIL           VARCHAR2(100),                       -- opsional
    POIN_LOYALITAS  NUMBER(6)      DEFAULT 0 NOT NULL,
    TANGGAL_DAFTAR  DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_PELANGGAN            PRIMARY KEY (ID_PELANGGAN),
    CONSTRAINT UK_PELANGGAN_NO_TELEPON UNIQUE (NO_TELEPON),
    CONSTRAINT CK_PELANGGAN_POIN       CHECK (POIN_LOYALITAS >= 0)
);

-- 2. KARYAWAN ---------------------------------------------------------
CREATE TABLE KARYAWAN (
    ID_KARYAWAN     NUMBER(10)
                    GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
                    NOT NULL,
    NAMA_KARYAWAN   VARCHAR2(100)  NOT NULL,
    JABATAN         VARCHAR2(30)   NOT NULL,             -- Kasir, Barista, Manajer
    NO_TELEPON      VARCHAR2(15)   NOT NULL,
    STATUS_AKTIF    VARCHAR2(15)   DEFAULT 'AKTIF' NOT NULL,
    CONSTRAINT PK_KARYAWAN         PRIMARY KEY (ID_KARYAWAN),
    CONSTRAINT CK_KARYAWAN_STATUS  CHECK (STATUS_AKTIF IN ('AKTIF', 'NONAKTIF'))
);

-- 3. MENU -------------------------------------------------------------
CREATE TABLE MENU (
    ID_MENU          NUMBER(10)
                     GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
                     NOT NULL,
    NAMA_MENU        VARCHAR2(100)  NOT NULL,
    KATEGORI         VARCHAR2(30)   NOT NULL,
    HARGA_SATUAN     NUMBER(10,2)   NOT NULL,
    STATUS_TERSEDIA  VARCHAR2(15)   DEFAULT 'TERSEDIA' NOT NULL,
    CONSTRAINT PK_MENU           PRIMARY KEY (ID_MENU),
    CONSTRAINT CK_MENU_KATEGORI  CHECK (KATEGORI IN ('KOPI', 'NON-KOPI', 'MAKANAN')),
    CONSTRAINT CK_MENU_HARGA     CHECK (HARGA_SATUAN >= 0),
    CONSTRAINT CK_MENU_STATUS    CHECK (STATUS_TERSEDIA IN ('TERSEDIA', 'HABIS'))
);

-- 4. BAHAN_BAKU -------------------------------------------------------
CREATE TABLE BAHAN_BAKU (
    ID_BAHAN       NUMBER(10)
                   GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
                   NOT NULL,
    NAMA_BAHAN     VARCHAR2(100)  NOT NULL,
    SATUAN_UKUR    VARCHAR2(20)   NOT NULL,
    STOK_TERSEDIA  NUMBER(10,2)   NOT NULL,
    BATAS_MINIMUM  NUMBER(10,2)   NOT NULL,
    CONSTRAINT PK_BAHAN_BAKU      PRIMARY KEY (ID_BAHAN),
    CONSTRAINT CK_BAHAN_SATUAN    CHECK (SATUAN_UKUR IN ('GRAM', 'ML', 'PCS')),
    CONSTRAINT CK_BAHAN_STOK      CHECK (STOK_TERSEDIA >= 0),
    CONSTRAINT CK_BAHAN_MINIMUM   CHECK (BATAS_MINIMUM >= 0)
);

-- 5. TRANSAKSI --------------------------------------------------------
-- ID_PELANGGAN boleh NULL (pembeli umum / walk-in customer)
CREATE TABLE TRANSAKSI (
    ID_TRANSAKSI     NUMBER(12)
                     GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
                     NOT NULL,
    ID_PELANGGAN     NUMBER(10),                          -- opsional
    ID_KARYAWAN      NUMBER(10)     NOT NULL,
    WAKTU_TRANSAKSI  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    METODE_BAYAR     VARCHAR2(20)   NOT NULL,
    TOTAL_BAYAR      NUMBER(12,2)   NOT NULL,
    CATATAN_PESANAN  VARCHAR2(255),                       -- opsional
    CONSTRAINT PK_TRANSAKSI            PRIMARY KEY (ID_TRANSAKSI),
    CONSTRAINT FK_TRANSAKSI_PELANGGAN  FOREIGN KEY (ID_PELANGGAN)
                                       REFERENCES PELANGGAN (ID_PELANGGAN),
    CONSTRAINT FK_TRANSAKSI_KARYAWAN   FOREIGN KEY (ID_KARYAWAN)
                                       REFERENCES KARYAWAN (ID_KARYAWAN),
    CONSTRAINT CK_TRANSAKSI_METODE     CHECK (METODE_BAYAR IN ('TUNAI', 'QRIS', 'DEBIT')),
    CONSTRAINT CK_TRANSAKSI_TOTAL      CHECK (TOTAL_BAYAR >= 0)
);

-- 6. DETAIL_TRANSAKSI -------------------------------------------------
CREATE TABLE DETAIL_TRANSAKSI (
    ID_DETAIL             NUMBER(12)
                          GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
                          NOT NULL,
    ID_TRANSAKSI          NUMBER(12)    NOT NULL,
    ID_MENU               NUMBER(10)    NOT NULL,
    JUMLAH_BELI           NUMBER(5)     NOT NULL,
    HARGA_SAAT_TRANSAKSI  NUMBER(10,2)  NOT NULL,         -- snapshot harga
    SUBTOTAL              NUMBER(12,2)  NOT NULL,
    CONSTRAINT PK_DETAIL_TRANSAKSI        PRIMARY KEY (ID_DETAIL),
    CONSTRAINT FK_DETAIL_TRANSAKSI        FOREIGN KEY (ID_TRANSAKSI)
                                          REFERENCES TRANSAKSI (ID_TRANSAKSI),
    CONSTRAINT FK_DETAIL_MENU             FOREIGN KEY (ID_MENU)
                                          REFERENCES MENU (ID_MENU),
    CONSTRAINT CK_DETAIL_JUMLAH           CHECK (JUMLAH_BELI > 0),
    CONSTRAINT CK_DETAIL_HARGA            CHECK (HARGA_SAAT_TRANSAKSI >= 0),
    -- Aturan satu baris: subtotal harus = jumlah x harga
    CONSTRAINT CK_DETAIL_SUBTOTAL         CHECK (SUBTOTAL = JUMLAH_BELI * HARGA_SAAT_TRANSAKSI)
);

-- 7. KOMPOSISI_MENU ---------------------------------------------------
CREATE TABLE KOMPOSISI_MENU (
    ID_KOMPOSISI   NUMBER(10)
                   GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 100)
                   NOT NULL,
    ID_MENU        NUMBER(10)   NOT NULL,
    ID_BAHAN       NUMBER(10)   NOT NULL,
    TAKARAN_PAKAI  NUMBER(8,2)  NOT NULL,
    CONSTRAINT PK_KOMPOSISI_MENU    PRIMARY KEY (ID_KOMPOSISI),
    CONSTRAINT FK_KOMPOSISI_MENU    FOREIGN KEY (ID_MENU)
                                    REFERENCES MENU (ID_MENU),
    CONSTRAINT FK_KOMPOSISI_BAHAN   FOREIGN KEY (ID_BAHAN)
                                    REFERENCES BAHAN_BAKU (ID_BAHAN),
    CONSTRAINT CK_KOMPOSISI_TAKARAN CHECK (TAKARAN_PAKAI > 0)
);

-- ---------------------------------------------------------------------
-- Index pada kolom FK (Oracle tidak membuatnya otomatis)
-- ---------------------------------------------------------------------
CREATE INDEX IDX_TRANSAKSI_PELANGGAN ON TRANSAKSI (ID_PELANGGAN);
CREATE INDEX IDX_TRANSAKSI_KARYAWAN  ON TRANSAKSI (ID_KARYAWAN);
CREATE INDEX IDX_DETAIL_TRANSAKSI    ON DETAIL_TRANSAKSI (ID_TRANSAKSI);
CREATE INDEX IDX_DETAIL_MENU         ON DETAIL_TRANSAKSI (ID_MENU);
CREATE INDEX IDX_KOMPOSISI_MENU      ON KOMPOSISI_MENU (ID_MENU);
CREATE INDEX IDX_KOMPOSISI_BAHAN     ON KOMPOSISI_MENU (ID_BAHAN);

-- ---------------------------------------------------------------------
-- Pemeriksaan cepat: ketujuh tabel harus muncul (7 baris)
-- ---------------------------------------------------------------------
SELECT table_name
FROM   user_tables
WHERE  table_name IN ('PELANGGAN','KARYAWAN','MENU','BAHAN_BAKU',
                      'TRANSAKSI','DETAIL_TRANSAKSI','KOMPOSISI_MENU')
ORDER  BY table_name;
